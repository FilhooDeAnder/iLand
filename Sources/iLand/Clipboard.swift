import Foundation
import AppKit

/// Item do histórico da área de transferência (texto, link ou arquivos).
struct ClipItem: Identifiable, Equatable {
    enum Kind: Equatable { case text, url, files }
    let id: UUID
    let kind: Kind
    let text: String        // texto, URL ou caminhos de arquivo (um por linha)
    let date: Date
    var pinned = false

    var preview: String { text.replacingOccurrences(of: "\n", with: " ⏎ ") }
    var fileURLs: [URL] { kind == .files ? text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) } : [] }
}

/// Remove parâmetros de rastreio de links (utm_*, fbclid, gclid...). O resto do link fica igual.
enum URLCleaner {
    private static let exact: Set<String> = ["fbclid", "gclid", "gbraid", "wbraid", "dclid", "msclkid", "mc_cid", "mc_eid", "igshid", "igsh",
                                             "_hsenc", "_hsmi", "yclid", "ttclid", "twclid", "li_fat_id", "ref_src", "ref_url", "si", "spm"]

    static func isTracking(_ name: String) -> Bool {
        let n = name.lowercased()
        return exact.contains(n) || n.hasPrefix("utm_") || n.hasPrefix("vero_") || n.hasPrefix("pk_")
    }

    /// nil se não é um link http(s) único.
    static func clean(_ s: String) -> String? {
        let t = s.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !t.contains(" "), !t.contains("\n"), var c = URLComponents(string: t), let scheme = c.scheme?.lowercased(),
              scheme == "http" || scheme == "https", c.host != nil else { return nil }
        let kept = c.queryItems?.filter { !isTracking($0.name) }
        c.queryItems = (kept?.isEmpty ?? true) ? nil : kept
        return c.string
    }
}

/// Histórico: novos na frente, sem repetir, fixados nunca saem, no máximo `max` itens soltos.
struct ClipHistory {
    private(set) var items: [ClipItem] = []
    var maxItems = 50
    static let maxLength = 20_000   // texto maior que isso não entra (evita guardar documentos inteiros)

    mutating func add(_ kind: ClipItem.Kind, _ text: String, now: Date = Date()) {
        guard !text.isEmpty, text.count <= Self.maxLength else { return }
        var pinned = false
        if let i = items.firstIndex(where: { $0.text == text && $0.kind == kind }) { pinned = items[i].pinned; items.remove(at: i) }
        items.insert(ClipItem(id: UUID(), kind: kind, text: text, date: now, pinned: pinned), at: 0)
        trim()
    }

    mutating func togglePin(_ id: UUID) {
        guard let i = items.firstIndex(where: { $0.id == id }) else { return }
        items[i].pinned.toggle()
    }

    mutating func remove(_ id: UUID) { items.removeAll { $0.id == id } }
    mutating func clearUnpinned() { items.removeAll { !$0.pinned } }
    mutating func setItems(_ list: [ClipItem]) { items = list }

    /// Fixados primeiro, depois os recentes; filtra por trecho (sem diferenciar maiúsculas/acentos).
    func visible(query: String) -> [ClipItem] {
        let q = query.trimmingCharacters(in: .whitespaces)
        let all = q.isEmpty ? items : items.filter { $0.text.range(of: q, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        return all.filter(\.pinned) + all.filter { !$0.pinned }
    }

    private mutating func trim() {
        var loose = 0
        items = items.filter { it in
            if it.pinned { return true }
            loose += 1
            return loose <= maxItems
        }
    }
}

/// Tipos que gerenciadores de senha e apps marcam como sensíveis ou temporários: nunca entram no histórico.
enum ClipboardPrivacy {
    static let skipTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
                                         "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType"]
    static let skipApps = ["com.1password", "com.agilebits", "com.bitwarden", "org.keepassxc", "com.lastpass", "com.dashlane", "com.apple.keychainaccess", "com.apple.Passwords"]

    static func shouldSkip(types: [String], frontApp: String?) -> Bool {
        if types.contains(where: skipTypes.contains) { return true }
        if let f = frontApp, skipApps.contains(where: { f.hasPrefix($0) }) { return true }
        return false
    }
}

/// Observa a área de transferência (1 leitura barata de changeCount a cada 1,5 s) e guarda o histórico em memória.
/// Só os itens FIXADOS são salvos em disco (pasta 0700); o resto some quando o app fecha.
final class ClipboardModel: ObservableObject {
    @Published private(set) var history = ClipHistory()
    @Published var query = ""
    @Published var autoClean = false         // limpar links rastreados sozinho ao copiar
    @Published private(set) var copiedID: UUID?
    private var lastCount = NSPasteboard.general.changeCount
    private var ignoreCount = -1
    private var timer: Timer?
    private let file: URL

    init(directory: URL? = nil) {
        let dir = directory ?? FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0].appendingPathComponent("iLand")
        try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        try? FileManager.default.setAttributes([.posixPermissions: 0o700], ofItemAtPath: dir.path)
        file = dir.appendingPathComponent("clipboard-pinned.json")
        loadPinned()
    }

    func start() {
        guard timer == nil else { return }
        let t = Timer.scheduledTimer(withTimeInterval: 1.5, repeats: true) { [weak self] _ in self?.poll() }
        t.tolerance = 1
        timer = t
    }

    var visible: [ClipItem] { history.visible(query: query) }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        guard pb.changeCount != ignoreCount else { return }
        let types = (pb.types ?? []).map(\.rawValue)
        if ClipboardPrivacy.shouldSkip(types: types, frontApp: NSWorkspace.shared.frontmostApplication?.bundleIdentifier) { return }
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            history.add(.files, urls.map(\.path).joined(separator: "\n"))
        } else if let s = pb.string(forType: .string) {
            if let cleaned = URLCleaner.clean(s) {
                if autoClean, cleaned != s.trimmingCharacters(in: .whitespacesAndNewlines) { writeBack(cleaned) }
                history.add(.url, autoClean ? cleaned : s.trimmingCharacters(in: .whitespacesAndNewlines))
            } else {
                history.add(.text, s)
            }
        }
        savePinned()
    }

    /// Copia o item de volta para a área de transferência (e sobe ele para o topo).
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        if item.kind == .files { pb.writeObjects(item.fileURLs as [NSURL]) } else { pb.setString(item.text, forType: .string) }
        ignoreCount = pb.changeCount; lastCount = pb.changeCount
        history.add(item.kind, item.text)
        copiedID = history.items.first?.id
        DispatchQueue.main.asyncAfter(deadline: .now() + 1.5) { [weak self] in self?.copiedID = nil }
    }

    /// Troca um link por ele mesmo sem rastreio (botão "limpar").
    func clean(_ item: ClipItem) {
        guard item.kind == .url, let c = URLCleaner.clean(item.text) else { return }
        let was = item.pinned
        history.remove(item.id); history.add(.url, c)
        if was, let id = history.items.first?.id { history.togglePin(id) }
        copy(history.items[0]); savePinned()
    }

    func togglePin(_ item: ClipItem) { history.togglePin(item.id); savePinned() }
    func remove(_ item: ClipItem) { history.remove(item.id); savePinned() }
    func clearUnpinned() { history.clearUnpinned() }

    private func writeBack(_ s: String) {
        let pb = NSPasteboard.general
        pb.clearContents(); pb.setString(s, forType: .string)
        ignoreCount = pb.changeCount; lastCount = pb.changeCount
    }

    // MARK: fixados em disco
    private struct Saved: Codable { let kind: String; let text: String; let date: Date }

    private var lastSaved: [String] = []

    private func savePinned() {
        let signature = history.items.filter(\.pinned).map { "\($0.kind)|\($0.text)" }
        guard signature != lastSaved else { return }   // nada mudou nos fixados: sem escrita em disco
        lastSaved = signature
        let list = history.items.filter(\.pinned).map { Saved(kind: $0.kind == .url ? "url" : ($0.kind == .files ? "files" : "text"), text: $0.text, date: $0.date) }
        if let data = try? JSONEncoder().encode(list) { try? data.write(to: file, options: .atomic); try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: file.path) }
    }

    private func loadPinned() {
        guard let data = try? Data(contentsOf: file), let list = try? JSONDecoder().decode([Saved].self, from: data) else { return }
        history.setItems(list.map { ClipItem(id: UUID(), kind: $0.kind == "url" ? .url : ($0.kind == "files" ? .files : .text), text: $0.text, date: $0.date, pinned: true) })
    }
}
